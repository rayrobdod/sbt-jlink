	private def perScopeSettings(config:sbt.librarymanagement.Configuration) = {
		inConfig(config)(Seq(
			classpathToModuleJdepsPhantoms := {
				val conv = fileConverter.value
				val tempDirectory = ((config / target).value / "classpathToModule").toPath

				val scalaAnyKindClass = locally:
					val entry = "scala/AnyKind.class"
					val outputFile = tempDirectory / entry
					Files.createDirectories(outputFile.getParent)
					buildScalaAnyKindClassTo(outputFile)

					val vf: xsbti.VirtualFile = conv.toVirtualFile(outputFile)
					Def.declareOutput(vf)
					vf -> entry

				Seq(
					scalaAnyKindClass,
				)
			},

			classpathToModuleModuleName := {
				val conv = fileConverter.value
				val sources = fullClasspath.value
					.map: source =>
						conv.toPath(source.data)
					.filter: source =>
						isJarEffectivelyNonEmpty(source)

				if 1 == sources.size then
					val source = sources(0)
					GetModuleName.ofAutomaticJar(source)
						.getOrElse(sys.error(s"$source does not have an Automatic-Module-Name"))
				else if 0 == sources.size then
					sys.error("No discovered module name since no non-empty jars are in classpath")
				else
					sys.error("No discovered module name since more than one non-empty jars is in classpath")
			},
			classpathToModuleModuleInfo := {
				val conv = fileConverter.value
				val stream = (classpathToModule / streams).value
				val logger = stream.log
				val tempDirectory = ((config / target).value / s"classpathToModule-jdeps-${config.name}").toPath
				val tempJdepsFile = ((config / target).value / s"classpathToModule-jdeps-${config.name}.jar").toPath

				val sources = fullClasspath.value.map(avf => conv.toPath(avf.data))

				val (requires, opens) = usingNewFileSystems(sources): sourceFileSystems =>
					val (mapping2, opens1) = mappingsFromJars(
						logger,
						tempDirectory,
						classpathToModuleModuleMergeStrategy.value,
						sourceFileSystems,
					)

					Files.deleteIfExists(tempJdepsFile)

					Using.resource(FileSystems.newFileSystem(tempJdepsFile, java.util.Map.of("create", true, "compressionMethod", "STORED"))): tempJdepsFs =>
						mapping2.foreach: (entryName, copyFrom) =>
							val entryPath = tempJdepsFs.getPath(entryName)
							if null != entryPath.getParent then
								Files.createDirectories(entryPath.getParent)
							Files.copy(copyFrom, entryPath, StandardCopyOption.COPY_ATTRIBUTES)
						classpathToModuleJdepsPhantoms.value.foreach: (copyFromVF, entryName) =>
							val copyFrom = conv.toPath(copyFromVF)
							val entryPath = tempJdepsFs.getPath(entryName)
							if null != entryPath.getParent then
								Files.createDirectories(entryPath.getParent)
							Files.copy(copyFrom, entryPath, StandardCopyOption.COPY_ATTRIBUTES)

					val requires1 = locally:
						val jdepsArgs = locally:
							val builder = Vector.newBuilder[String]

							builder += "--print-module-deps"

							if dependencyModulepath.value.nonEmpty then
								given xsbti.FileConverter = conv
								builder += "--module-path"
								builder += (dependencyModulepath).value.files.mkString(java.io.File.pathSeparator)
							end if

							builder += tempJdepsFile.toString

							builder.result()
						logger.debug(jdepsArgs.mkString(" "))

						RunTool(
							"jdeps",
							jdepsArgs,
							stream,
							"jdeps",
						)

						Using.resource(stream.readText(stream.key, "jdeps.out")): toolout =>
							val is = new java.io.StringWriter
							toolout.transferTo(is)
							is.toString.strip.split(",").to(Vector)

					(requires1, opens1.to(Vector))

				ClasspathToModuleModuleInfo(
					moduleName = classpathToModuleModuleName.value,
					moduleVersion = None,
					requires = requires,
					exports = opens,
					opens = opens,
					uses = Vector.empty,
					provides = Map.empty,
				)
			},


			classpathToModuleModuleInfoClass / artifactPath := {
				val conv = fileConverter.value
				val tempDirectory = (target.value / s"classpathToModule-${config.name}").toPath
				val entry = "module-info.class"
				conv.toVirtualFile(tempDirectory / entry)
			},
			classpathToModuleModuleInfoClass := {
				val conv = fileConverter.value
				val data = classpathToModuleModuleInfo.value
				val entry = "module-info.class"
				val outputFile = conv.toPath((classpathToModuleModuleInfoClass / artifactPath).value)

				java.nio.file.Files.createDirectories(outputFile.getParent)

				java.lang.classfile.ClassFile.of().buildModuleTo(
					outputFile,
					java.lang.classfile.attribute.ModuleAttribute.of(
						java.lang.constant.ModuleDesc.of(data.moduleName),
						moduleBuilder =>
							data.moduleVersion.foreach: `moduleVersion` =>
								moduleBuilder.moduleVersion(
									`moduleVersion`,
								)
							data.requires.foreach: `require` =>
								moduleBuilder.requires(
									java.lang.constant.ModuleDesc.of(`require`),
									java.lang.classfile.ClassFile.ACC_TRANSITIVE,
									null,
								)
							data.exports.foreach: `export` =>
								moduleBuilder.exports(
									java.lang.constant.PackageDesc.of(`export`),
									0,
								)
							data.opens.foreach: `open` =>
								moduleBuilder.opens(
									java.lang.constant.PackageDesc.of(`open`),
									0,
								)
							data.uses.foreach: `use` =>
								moduleBuilder.uses(
									java.lang.constant.ClassDesc.of(`use`),
								)
							data.provides.foreach: (service, instances) =>
								moduleBuilder.provides(
									java.lang.constant.ClassDesc.of(service),
									instances.map(java.lang.constant.ClassDesc.of)*
								)
					)
				)

				val vf: xsbti.VirtualFile = conv.toVirtualFile(outputFile)
				Def.declareOutput(vf)
				vf -> entry
			},


			classpathToModule / artifact := {
				Defaults.artifactSetting.value
					.withClassifier(Option("classpathToModule"))
					.withExtension("jar")
			},
			classpathToModule / artifactPath := Defaults.artifactPathSetting(classpathToModule / artifact).value,
			classpathToModule := {
				val conv = fileConverter.value
				val stream = (classpathToModule / streams).value
				val logger = stream.log
				val tempDirectory = ((config / target).value / s"classpathToModule-${config.name}").toPath
				val outputFile = conv.toPath((classpathToModule / artifactPath).value)

				val sources = fullClasspath.value.map(avf => conv.toPath(avf.data))

				usingNewFileSystems(sources): sourceFileSystems =>
					val (mapping2, opens1) = mappingsFromJars(
						logger,
						tempDirectory,
						classpathToModuleModuleMergeStrategy.value,
						sourceFileSystems,
					)

					Files.deleteIfExists(outputFile)
					Using.resource(FileSystems.newFileSystem(outputFile, java.util.Map.of("create", true))): outputFs =>
						mapping2.foreach: (entryName, copyFrom) =>
							val entryPath = outputFs.getPath(entryName)
							if null != entryPath.getParent then
								Files.createDirectories(entryPath.getParent)
							Files.copy(copyFrom, entryPath, StandardCopyOption.COPY_ATTRIBUTES)

						val (moduleInfoContentsVF, moduleInfoEntryName) = classpathToModuleModuleInfoClass.value
						val entryPath = outputFs.getPath(moduleInfoEntryName)
						if null != entryPath.getParent then
							Files.createDirectories(entryPath.getParent)
						Files.copy(conv.toPath(moduleInfoContentsVF), entryPath, StandardCopyOption.COPY_ATTRIBUTES)
						(classpathToModule / packageTimestamp).value.foreach: epoch =>
							Files.setLastModifiedTime(entryPath, attribute.FileTime.from(java.time.Instant.ofEpochMilli(epoch)))

				val vf: xsbti.VirtualFile = conv.toVirtualFile(outputFile)
				Def.declareOutput(vf)
				vf: xsbti.HashedVirtualFileRef
			},

			exportedModulepath += classpathToModule.value,
			exportedAddModules += classpathToModuleModuleName.value,
		))
	}

	override lazy val projectSettings = unscopedSettings ++ perScopeSettings(Compile) ++ perScopeSettings(Test)
end ClasspathToModulePlugin

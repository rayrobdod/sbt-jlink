	private def buildScalaAnyKindClassTo(outputPath: Path): Unit =
		java.lang.classfile.ClassFile.of().buildTo(
			outputPath,
			java.lang.constant.ClassDesc.of("scala", "AnyKind"),
			(classBuilder: java.lang.classfile.ClassBuilder) =>
				classBuilder.withFlags(
					java.lang.reflect.AccessFlag.PUBLIC,
					java.lang.reflect.AccessFlag.FINAL,
				)
		)
	end buildScalaAnyKindClassTo

	private def usingNewFileSystems[A](sources: Seq[Path])(fn: Seq[FileSystem] => A):A =
		val openedFileSystems = scala.collection.mutable.Buffer[FileSystem]()

		try
			sources.foreach: source =>
				val fs = FileSystems.newFileSystem(source)
				openedFileSystems += fs

			fn(openedFileSystems.to(Vector))

		finally
			openedFileSystems.foreach: fs =>
				fs.close()
	end usingNewFileSystems

	private final class RecordingFileVisitor extends FileVisitor[Path]:
		private var _baseDirectory: Path = null
		private val mapping = Vector.newBuilder[(Path, String)]
		private val exports = scala.collection.immutable.SortedSet.newBuilder[String]

		override def postVisitDirectory(path: Path, ex: java.io.IOException): FileVisitResult =
			FileVisitResult.CONTINUE

		override def preVisitDirectory(path: Path, attrs: attribute.BasicFileAttributes): FileVisitResult =
			FileVisitResult.CONTINUE

		override def visitFile(path: Path, attrs: attribute.BasicFileAttributes): FileVisitResult =
			if path.getFileName.toString.endsWith(".class") then
				val parentPath = path.getParent
				if _baseDirectory != parentPath then
					import scala.jdk.CollectionConverters.IterableHasAsScala
					val relativizedPath = _baseDirectory.relativize(parentPath)
					if ! relativizedPath.startsWith("META-INF") then
						exports += relativizedPath.asScala.mkString(".")
			end if
			mapping += path -> _baseDirectory.relativize(path).toString
			FileVisitResult.CONTINUE

		override def visitFileFailed(path: Path, ex: java.io.IOException): FileVisitResult =
			FileVisitResult.TERMINATE


		def baseDirectory: Path = this._baseDirectory
		def baseDirectory_=(newValue: Path): Unit = this._baseDirectory = newValue
		def mappingResult(): Vector[(Path, String)] = mapping.result()
		def exportsResult(): scala.collection.immutable.SortedSet[String] = exports.result()
	end RecordingFileVisitor

	private def mappingsFromJars(
		logger: sbt.Logger,
		tempDirectory: Path,
		mergeStrategy: MergeStrategyChooser,
		sourceFileSystems: Seq[FileSystem],
	): (Vector[(String, Path)], Vector[String]) =
		val (mapping1, opens1) = locally:
			val recorder = new RecordingFileVisitor()

			sourceFileSystems.foreach: fileSystem =>
				fileSystem.getRootDirectories.forEach: rootDir =>
					recorder.baseDirectory = rootDir
					Files.walkFileTree(rootDir, recorder)

			(recorder.mappingResult(), recorder.exportsResult())

		val mapping2 = mapping1
			.groupMap(_._2)(_._1)
			.map: (outEntryName, srcs) =>
				outEntryName -> mergeStrategy.apply(outEntryName, srcs, tempDirectory, logger)

			.to(Vector)

		(mapping2, opens1.to(Vector))
	end mappingsFromJars

	/**
	 * Intended to filter out a `compile` with no sources, but also conveniently filters out classless `scala3-library_3` artifacts
	 */
	private def isJarEffectivelyNonEmpty(sourceFile: Path): Boolean =

		final class CheckEffectivelyNonEmptyFileVisitor extends FileVisitor[Path]:
			var result: Boolean = false

			override def postVisitDirectory(path: Path, ex: java.io.IOException): FileVisitResult =
				FileVisitResult.CONTINUE

			override def preVisitDirectory(path: Path, attrs: attribute.BasicFileAttributes): FileVisitResult =
				FileVisitResult.CONTINUE

			override def visitFile(path: Path, attrs: attribute.BasicFileAttributes): FileVisitResult =
				if path.endsWith("META-INF/MANIFEST.MF") then
					FileVisitResult.CONTINUE
				else
					result = true
					FileVisitResult.TERMINATE

			override def visitFileFailed(path: Path, ex: java.io.IOException): FileVisitResult =
				FileVisitResult.TERMINATE

		end CheckEffectivelyNonEmptyFileVisitor

		val visitor = new CheckEffectivelyNonEmptyFileVisitor
		Using.resource(FileSystems.newFileSystem(sourceFile)): fileSystem =>
			fileSystem.getRootDirectories.forEach: rootDir =>
				Files.walkFileTree(rootDir, visitor)
		visitor.result
	end isJarEffectivelyNonEmpty


